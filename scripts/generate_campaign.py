"""Generate the private campaign's server/client records from one UTF-8 manifest.

No maps, monsters, sprites, classes or items are created by this generator.
Run with --check in validation to detect drift without changing files.
"""
from pathlib import Path
import json,re,sys,struct,zlib,hashlib
ROOT=Path(__file__).resolve().parent.parent
SERVER=ROOT/'source/nostalre-launcher/server'
CLIENT=ROOT/'source/nostalre-launcher/client'
ROMFS=CLIENT/'switch/romfs/server'
manifest=json.loads((ROOT/'campaign/pre-renewal/campaign.yml').read_text(encoding='utf8'))
check='--check' in sys.argv
q=lambda s:json.dumps(s,ensure_ascii=False)
outputs={}
def output(path,text):outputs[path]=text.encode('utf8')
visited=set();texts={};active=set();edges=[]
def visit(rel):
 if rel in visited:return
 visited.add(rel);path=SERVER/rel
 if not path.is_file():return
 data=path.read_bytes()
 try:text=data.decode('utf8')
 except UnicodeDecodeError:text=data.decode('cp1252')
 texts[rel]=text
 for line in text.splitlines():
  line=line.split('//',1)[0].strip()
  found=re.match(r'(?:npc|import):\s*(\S+)',line)
  if found:visit(found[1]);continue
  found=re.match(r'([\w@-]+),[^\t]*\t(?:script|warp|monster|boss_monster|duplicate\()',line)
  if found:active.add(found[1])
  found=re.match(r'([\w@-]+),(\d+),(\d+),\d+\twarp\t[^\t]+\t\d+,\d+,([\w@-]+),(\d+),(\d+)',line)
  if found:edges.append((found[1],int(found[2]),int(found[3]),found[4]))
visit('npc/pre-re/scripts_main.conf')
world={}
for rel in ['db/map_cache.dat','db/pre-re/map_cache.dat','db/import/map_cache.dat']:
 data=(ROMFS/rel).read_bytes();_,n=struct.unpack_from('<IH',data);offset=8
 for _ in range(n):
  name,w,h,size=struct.unpack_from('<12shhi',data,offset);offset+=20
  cells=zlib.decompress(data[offset:offset+size]);offset+=size
  world[name.split(b'\0')[0].decode()]=(w,h,cells)
def walkable(mp,x,y):
 if mp not in world:return False
 w,h,cells=world[mp]
 return 0<=x<w and 0<=y<h and cells[y*w+x] in (0,2,3,4,6)
def safe(mp,x,y):
 for radius in range(12):
  for dx in range(-radius,radius+1):
   for dy in range(-radius,radius+1):
    if walkable(mp,x+dx,y+dy):return x+dx,y+dy
 raise ValueError((mp,x,y))
stages=manifest['stages'];assert len(stages)<100
mob_db=(SERVER/'db/pre-re/mob_db.yml').read_text(encoding='utf8')
for index,st in enumerate(stages):
 assert st['id']==900000+index and st['id']*1000+999<2**31
 assert st['map'] in active and st['area'] in active
 assert walkable(st['map'],st['x'],st['y']) and walkable(st['area'],st['area_x'],st['area_y']),st
 if st['mob']:
  assert re.search(r'  - Id: '+str(st['mob'])+r'\n',mob_db),st
  assert st['kind']=='boss' or any(re.search(r'^'+st['area']+r',[^\n]*\tmonster\t[^\n]*[,\t]'+str(st['mob'])+r',',t,re.M) for t in texts.values()),st
for rel in ['db/pre-re/quest_db.yml','db/re/quest_db.yml','db/import/quest_db.yml']:
 path=SERVER/rel
 if path.exists():assert not re.search(r'^\s*- Id: 900\d{3}\s*$',path.read_text(encoding='utf8'),re.M),rel
# Stable schema-1 stage order and atomic-reward reference levels.
kind={'talk':0,'hunt':1,'collect':2,'class':3,'boss':4}
cpp=['// Generated by scripts/generate_campaign.py. Edit campaign.yml.','static const CampaignStage campaign_stages[] = {']
for st in stages:
 values=[q(st['npc_internal']),q(st['map']),str(st['x']),str(st['y']),str(kind[st['kind']]),q(st['area'])]+[str(st[k]) for k in ['mob','count','item','goal','jobgoal','zeny','area_x','area_y']]
 cpp.append('{'+','.join(values)+'},')
cpp+=['};',''];output(SERVER/'src/map/campaign_data.inc','\n'.join(cpp))
# Imported native quest DB carries only the counter shape; SQLite owns progress.
quest=['Header:','  Type: QUEST_DB','  Version: 3','Body:']
for st in stages:
 quest += [f'  - Id: {st["id"]}',f'    Title: {q(st["title"])}']
 if st['mob']:quest+=['    Targets:',f'      - Mob: {st["aegis"]}',f'        Count: {st["count"]}']
quest+=['  - Id: 900999','    Title: "Ecos de Rune-Midgard - Campanha concluída"','']
for st in stages:quest += [f'  - Id: {st["id"]+500}',f'    Title: {q(st["title"]+" - Concluída")}']
for base in [SERVER,ROMFS]:output(base/'db/ragswitch_campaign_quests.yml','\n'.join(quest)+'\n')
rust=['// Generated from campaign/pre-renewal/campaign.yml.',"pub struct Stage { pub id:u32, pub title:&'static str, pub objective:&'static str, pub summary:&'static str, pub map:&'static str, pub x:u16, pub y:u16, pub npc:&'static str, pub area:&'static str, pub ax:u16, pub ay:u16, pub hunt:bool }",'pub static STAGES:&[Stage]=&[']
for st in stages:
 values=f'id:{st["id"]},title:{q(manifest["chapters"][st["chapter"]]+" - "+st["title"])},objective:{q(st["objective"])},summary:{q(st["story"]+chr(10)*2+st["result"])},map:{q(st["map"])},x:{st["x"]},y:{st["y"]},npc:{q(st["display_npc"])},area:{q(st["area"])},ax:{st["area_x"]},ay:{st["area_y"]},hunt:{str(bool(st["mob"])).lower()}'
 rust.append('Stage {'+values+'},')
rust+= ['];','pub static ROUTES:&[(&str,u16,u16,&str)] = &[']
for a,x,y,b in sorted(set(edges)):
 if a not in active or b not in active:continue
 try:x,y=safe(a,x,y)
 except ValueError:continue
 rust.append(f'({q(a)},{x},{y},{q(b)}),')
rust+= ['];',''];output(CLIENT/'lib/game/src/campaign_data.rs','\n'.join(rust))
hooks={}
for i,st in enumerate(stages):hooks.setdefault((st['file'],st['npc_internal']),[]).append(i)
output(CLIENT/'client/src/campaign_hooks.tsv',''.join(p+'\t'+npc+'\t'+' || '.join('RS_CampStage == '+str(i) for i in ids)+'\n' for (p,npc),ids in hooks.items()))
# The authored script is generated from manifest text, preserving native sidequest flags.
script=['// Generated campaign dialogue, UTF-8. Original classic sidequests remain available.','function\tscript\tRS_CampaignContact\t{','  .@key$=getarg(0);','  .@step=campaign(0);','  switch (.@step) {']
for i,st in enumerate(stages):
 script += [f'    case {i}:',f'      if (.@key$ != {q(st["npc_internal"])}) return 0;',f'      mes {q("["+st["title"]+"]")};',f'      mes {q(manifest["chapters"][st["chapter"]])};',f'      mes {q(st["story"])};','      next;']
 if st['kind']=='boss':
  script += ['      .@choice=select("Iniciar ou retomar confronto:Entregar vitória:Reagrupar companheiros:Conversar sobre outro assunto:Sair");','      if (.@choice==1) {','        if (campaign(3)) { close2; warp "moc_fild21",38,193; end; }','        mes "A tentativa não pôde iniciar. Reagrupe e tente novamente. Um confronto público em andamento precisa terminar antes de iniciar o seu."; return 1;','      }','      if (.@choice==3) { campaign(4); mes "Equipe reagrupada. Companheiros derrotados só se recuperam fora do confronto."; return 1; }','      if (.@choice==4) return 0;','      if (.@choice!=2) return 1;']
 else:
  other='Abrir Job Changer' if st['kind']=='class' else 'Conversar sobre outro assunto'
  script += [f'      .@choice=select("Confirmar e entregar:Reagrupar companheiros:{other}:Sair");','      if (.@choice==2) { campaign(4); mes "Sua equipe foi chamada de volta."; return 1; }','      if (.@choice==3) return 0;','      if (.@choice!=1) return 1;']
 script += [f'      if (!campaign(1,{i})) {{ mes "Ainda falta cumprir o objetivo do diário. Confirme o local, os alvos, materiais ou requisitos de classe. Sua etapa permanece salva."; return 1; }}']
 if i==2:script+=['      skill "NV_FIRSTAID",1,0;']
 script+=[f'      mes {q(st["result"])};']
 destinations={0:'warp "new_1-2",100,25;',1:'warp "new_1-2",100,70;',2:'warp "new_1-3",95,30;',3:'savepoint "prontera",149,178; warp "prontera",149,178;'}
 if i in destinations:script+=['      next; close2; '+destinations[i]+' end;']
 script+=['      return 1;']
script+=['  }','  return 0;','}','-\tscript\tRS_Campaign\t-1,{','OnPCLoginEvent:','  campaign(0);','  if (RS_CampStage >= 3 && getskilllv("NV_FIRSTAID") == 0) skill "NV_FIRSTAID",1,0;','  end;','}','function\tscript\tRS_CampaignMenu\t{','  .@step=campaign(0);','  .@resume=(.@step < 4 && strpos(strcharinfo(3),"new_") != 0);','  mes "[Ecos de Rune-Midgard]";','  if (.@resume) mes "Uma etapa do treinamento ficou pendente. Retomar treinamento leva voce ao instrutor ou examinador correto sem apagar sua classe nem seu progresso.";','  if (.@step >= 33) mes "CAMPANHA CONCLU\u00cdDA. O mundo aberto e seus companheiros continuam dispon\u00edveis. Ver objetivo abre o registro do final.";','  mes "Acompanhe a missão no diário. O elenco fica salvo por personagem. Lira protege, Caio causa dano e Nara cuida do suporte. Eles evoluem com sua classe e contam no limite de 50 bots.";','  switch(select((.@resume ? "Retomar treinamento" : "Ver objetivo")+":Recrutar ou dispensar companheiros:Reagrupar companheiros:Viajar ao objetivo atual:Voltar ao atendimento")) {','    case 1: if (.@resume) { close2; campaign(5); end; } if (.@step >= 33) open_quest_ui 900999; else open_quest_ui; return;','    case 2: if (campaign(2) < 0) { mes "Retire-se do confronto antes de alterar seus companheiros."; return; } mes "Elenco atualizado. O número de companheiros aparece no chat. Novos recrutas começam como aprendizes quando você também é aprendiz."; return;','    case 3: campaign(4); mes "Equipe chamada de volta. Durante o chefe, derrotados aguardam sua retirada para se recuperar."; return;','    case 4: close2; campaign(5); end;','  }','  return;','}']
for base in [SERVER,ROMFS]:output(base/'npc/custom/ragswitch_campaign/main.txt','\n'.join(script)+'\n')
for path,data in outputs.items():
 if check:assert path.read_bytes()==data,'Generated campaign drift: '+str(path)
 elif not path.is_file() or path.read_bytes()!=data:path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(data)
report=dict(passed=True,stages=len(stages),existing_contacts=len(hooks),active_files=len(visited),route_edges=len(set(edges)),new_maps=0,new_monsters=0,new_items=0,new_art=0,manifest_sha256=hashlib.sha256((ROOT/'campaign/pre-renewal/campaign.yml').read_bytes()).hexdigest())
(ROOT/'evidence/campaign-content.json').write_text(json.dumps(report,indent=2)+'\n',encoding='utf8')
print('CAMPAIGN_VALIDATED' if check else 'CAMPAIGN_GENERATED',len(stages),'stages;',len(outputs),'private records')
