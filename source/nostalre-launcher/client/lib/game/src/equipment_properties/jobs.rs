/// `GetCategoryJob(n)` (0x68a1f0): the line's first, second, third or fourth job; 0 for any other n
pub fn category_job(n: i32, job: u16) -> i32 {
    match n {
        1 => pure_job(job),
        2 => second_job(job),
        3 => third_job(job),
        // 0x679ef0: as the third, but the fourth jobs give themselves
        4 if matches!(job, 4252..=4264 | 4302..=4308) => i32::from(job),
        4 => third_job(job),
        _ => 0,
    }
}

