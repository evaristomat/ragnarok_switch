#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_fourth_job_reads_its_line() {
        // Dragon Knight (4252): Swordman, Knight, Rune Knight, itself
        assert_eq!(pure_job(4252), 1);
        assert_eq!(category_job(2, 4252), 7);
        assert_eq!(category_job(3, 4252), 4054);
        assert_eq!(category_job(4, 4252), 4252);
        assert_eq!(category_job(5, 4252), 0);
        assert_eq!(job_group2(4252), 14);
    }

    #[test]
    fn unlisted_ids_fall_back_as_kros_switches_do() {
        assert_eq!(pure_job(0), 0);
        assert_eq!(category_job(2, 13), 13);
        assert_eq!(job_group2(13), 99);
    }
}
